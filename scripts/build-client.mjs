import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['sources/plugin/plugin-body.tsx'],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'BohrPlugin',
  external: ['react', 'react/jsx-runtime'],
  loader: { '.css': 'text' },
  minify: true,
  legalComments: 'none',
  target: ['es2020'],
});

const bundle = result.outputFiles[0].text;
const client = `/** Generated by scripts/build-client.mjs. React is supplied by DSH. */\nwindow.__ModuleLoader__.load({\n  id: '@local/bohr-research-atlas',\n  factory(require) {\n${bundle}\n    return {\n      inject: ['slots'],\n      apply(ctx) { return BohrPlugin.apply(ctx); },\n    };\n  },\n});\n`;
await writeFile('client.js', client, 'utf8');
console.log(`Built client.js (${Buffer.byteLength(client)} bytes)`);
